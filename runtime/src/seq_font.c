static uint8_t g_rows[95][SEQ_FONT_HEIGHT];
static int g_rows_ready = 0;

const uint8_t* seq_font_glyph(unsigned char c) {
  if (!g_rows_ready) {
    int glyph;
    for (glyph = 0; glyph < 95; ++glyph) {
      int row;
      for (row = 0; row < SEQ_FONT_HEIGHT; ++row) {
        uint8_t bits = 0;
        int column;
        for (column = 0; column < SEQ_FONT_WIDTH; ++column) {
          bits = (uint8_t)(bits << 1);
          if (kGlyphArt[glyph][row * SEQ_FONT_WIDTH + column] == '#') {
            bits |= 1U;
          }
        }
        g_rows[glyph][row] = bits;
      }
    }
    g_rows_ready = 1;
  }
  if (c < 32 || c > 126) {
    c = '?';
  }
  return g_rows[c - 32];
}
